'use strict';

const FAMILY_ID = 'electronics';

// Unico item: la raggiungibilità del dispositivo (allineato a ElectronicEntity dell'app)
const ITEMS = ['isOnline'];

/*----------------------------------------------------------------------------------------------------------------------
----------------------------------------------------------------------------------------------------------------------*/
function readableItems() {
    return ITEMS;
}

/*----------------------------------------------------------------------------------------------------------------------
----------------------------------------------------------------------------------------------------------------------*/
function editorItems() {
    return ITEMS;
}

/*----------------------------------------------------------------------------------------------------------------------
----------------------------------------------------------------------------------------------------------------------*/
function isOutputItem() {
    return true;
}

/*----------------------------------------------------------------------------------------------------------------------
----------------------------------------------------------------------------------------------------------------------*/
function outputValue(item, value) {
    return value;
}

/*----------------------------------------------------------------------------------------------------------------------
    Stato del nodo: "Online", "Offline" o "Unknown" se la headunit non ha ancora un valore
----------------------------------------------------------------------------------------------------------------------*/
function status(device) {
    if (typeof device.isOnline !== 'boolean') return { fill: 'grey', shape: 'ring', text: 'Unknown' };
    return device.isOnline ? { fill: 'green', shape: 'dot', text: 'Online' } : { fill: 'grey', shape: 'ring', text: 'Offline' };
}

module.exports = { FAMILY_ID, readableItems, editorItems, isOutputItem, outputValue, status };
